export type UiLocale = keyof typeof uiCopy

export function uiText(key: UiCopyKey, replacements: Record<string, string | number> = {}, locale: UiLocale = ACTIVE_UI_LOCALE): string {
  let text: string = uiCopy[locale][key] ?? uiCopy.en[key]
  for (const [token, value] of Object.entries(replacements)) {
    text = text.replaceAll(`{${token}}`, String(value))
  }
  return text
}

